import { readFileSync } from "node:fs";
import { resolve } from "node:path";
import nodemailer from "nodemailer";

// Load .env then .env.local (Next.js precedence: .env.local overrides .env)
const env = {};
for (const filename of [".env", ".env.local"]) {
  const path = resolve(process.cwd(), filename);
  let raw;
  try {
    raw = readFileSync(path, "utf8");
  } catch {
    continue;
  }
  for (const line of raw.split("\n")) {
    const trimmed = line.trim();
    if (!trimmed || trimmed.startsWith("#")) continue;
    const eq = trimmed.indexOf("=");
    if (eq === -1) continue;
    const key = trimmed.slice(0, eq).trim();
    let value = trimmed.slice(eq + 1);
    // Strip trailing inline comment when value is unquoted
    if (!value.trim().startsWith('"') && !value.trim().startsWith("'")) {
      const hash = value.indexOf("#");
      if (hash !== -1) value = value.slice(0, hash);
    }
    value = value.trim();
    if (
      (value.startsWith('"') && value.endsWith('"')) ||
      (value.startsWith("'") && value.endsWith("'"))
    ) {
      value = value.slice(1, -1);
    }
    env[key] = value;
  }
}

const cfg = {
  host: env.SMTP_HOST,
  port: Number(env.SMTP_PORT ?? 587),
  user: env.SMTP_USER,
  pass: env.SMTP_PASS,
  from: env.SMTP_FROM,
  to: env.NOTIFY_EMAIL,
};

console.log("→ SMTP host:", cfg.host);
console.log("→ SMTP port:", cfg.port);
console.log("→ SMTP user:", cfg.user);
console.log("→ SMTP from:", cfg.from);
console.log("→ Notify to:", cfg.to);
console.log("");

const missing = Object.entries(cfg).filter(([, v]) => !v).map(([k]) => k);
if (missing.length) {
  console.error("Missing env vars:", missing.join(", "));
  process.exit(1);
}

const transport = nodemailer.createTransport({
  host: cfg.host,
  port: cfg.port,
  secure: cfg.port === 465,
  auth: { user: cfg.user, pass: cfg.pass },
});

console.log("Verifying SMTP connection...");
try {
  await transport.verify();
  console.log("✅ SMTP connection verified.");
} catch (err) {
  console.error("❌ SMTP verify failed:");
  console.error(err);
  process.exit(1);
}

